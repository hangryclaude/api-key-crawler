package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"

	"keyguard/internal/pattern/rules"
)

// quote is a Go string literal for s: plain double quotes when nothing needs escaping, raw when
// escaping would only add backslashes (a regex), escaped otherwise.
func quote(s string) string {
	q := strconv.Quote(s)
	if q == `"`+s+`"` {
		return q
	}
	if !strings.ContainsAny(s, "`\r") && isPlain(s) {
		return "`" + s + "`"
	}
	return q
}

func isPlain(s string) bool {
	for _, r := range s {
		if r == '\t' || r == '\n' {
			continue
		}
		if r < 0x20 || r == 0x7f || r == 0xfeff {
			return false
		}
	}
	return true
}

func strs(v []string) string {
	q := make([]string, len(v))
	for i, s := range v {
		q[i] = quote(s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

func floatLit(f float64) string { return strconv.FormatFloat(f, 'g', -1, 64) }

func filterLit(f rules.Filter) string {
	var parts []string
	if f.Entropy.Min != 0 {
		e := "Floor{Min: " + floatLit(f.Entropy.Min)
		if f.Entropy.Strict {
			e += ", Strict: true"
		}
		parts = append(parts, "Entropy: "+e+"}")
	}
	if f.TokenRatio != 0 {
		parts = append(parts, "TokenRatio: "+floatLit(f.TokenRatio))
	}
	for _, kv := range []struct {
		name string
		v    []string
	}{{"DropRegex", f.DropRegex}, {"DropWords", f.DropWords}, {"DropSHA256", f.DropSHA256}, {"DropPath", f.DropPath}} {
		if len(kv.v) > 0 {
			parts = append(parts, kv.name+": "+strs(kv.v))
		}
	}
	if len(f.Require) > 0 {
		groups := make([]string, len(f.Require))
		for i, g := range f.Require {
			groups[i] = strs(g)
		}
		parts = append(parts, "Require: [][]string{"+strings.Join(groups, ", ")+"}")
	}
	if f.Residual != 0 {
		parts = append(parts, "Residual: "+strconv.Itoa(f.Residual))
	}
	return "Filter{" + strings.Join(parts, ", ") + "}"
}

// commitConst names the constant that holds a lineage's pinned commit.
func commitConst(lineage string) string {
	return "commit" + strings.ToUpper(lineage[:1]) + lineage[1:]
}

// emit is the text of rules_gen.go.
func emit(table []rules.Rule, global rules.Filter, commits map[string]string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/pattern/rulegen from rules/src/*.json and rules/keyguard.toml; DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Modified for keyguard: rule data published by other projects, re-expressed as a Go table. Each rule's Src\n")
	b.WriteString("// says whose it is, at which commit and under which licence; the notices are in THIRD_PARTY_NOTICES.md.\n\n")
	b.WriteString("package rules\n\n")

	lineages := make([]string, 0, len(commits))
	for l := range commits {
		lineages = append(lineages, l)
	}
	sort.Strings(lineages)
	b.WriteString("// The commits the upstream data was read at (rules/SOURCES.lock).\nconst (\n")
	for _, l := range lineages {
		fmt.Fprintf(&b, "\t%s = %q\n", commitConst(l), commits[l])
	}
	b.WriteString(")\n\n")

	b.WriteString("// Global is the filter betterleaks applies to every rule, after the rule's own.\n")
	fmt.Fprintf(&b, "var Global = %s\n\n", filterLit(global))

	b.WriteString("// All is the table, sorted by id.\nvar All = []Rule{\n")
	for _, r := range table {
		b.WriteString("\t{\n")
		field := func(name, val string) { fmt.Fprintf(&b, "\t\t%s: %s,\n", name, val) }
		field("ID", quote(r.ID))
		field("Provider", quote(r.Provider))
		if r.Desc != "" {
			field("Desc", quote(r.Desc))
		}
		if len(r.Keywords) > 0 {
			field("Keywords", strs(r.Keywords))
		}
		if r.Re != "" {
			field("Re", quote(r.Re))
		}
		if r.Group != 0 {
			field("Group", strconv.Itoa(r.Group))
		}
		if r.Path != "" {
			field("Path", quote(r.Path))
		}
		if r.Confidence != "" {
			field("Confidence", quote(r.Confidence))
		}
		field("Specificity", strconv.Itoa(r.Specificity)) // always: 0 is a value, not an absence
		if fl := filterLit(r.Filter); fl != "Filter{}" {
			field("Filter", fl)
		}
		if r.ComponentOnly {
			field("ComponentOnly", "true")
		}
		if len(r.Needs) > 0 {
			ns := make([]string, len(r.Needs))
			for i, n := range r.Needs {
				ns[i] = "{ID: " + quote(n.ID)
				if n.Within != "" {
					ns[i] += ", Within: " + quote(n.Within)
				}
				if n.Optional {
					ns[i] += ", Optional: true"
				}
				ns[i] += "}"
			}
			field("Needs", "[]Need{"+strings.Join(ns, ", ")+"}")
		}
		if r.Validates {
			field("Validates", "true")
		}
		src := "Src{Lineage: " + quote(r.Src.Lineage)
		if r.Src.UpstreamID != "" {
			src += ", UpstreamID: " + quote(r.Src.UpstreamID)
		}
		if r.Src.Commit != "" {
			src += ", Commit: " + commitConst(r.Src.Lineage)
		}
		src += ", Licence: " + quote(r.Src.Licence)
		if r.Src.Rewrite != "" {
			src += ", Rewrite: " + quote(r.Src.Rewrite)
		}
		field("Src", src+"}")
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("the generated file does not parse: %w", err)
	}
	return out, nil
}
